"""Turn a downloaded public_suffix_list.dat into psl.js, the frozen snapshot used by algorithm v2.

  python3 tools/make_psl.py PATH/TO/public_suffix_list.dat

Nothing in the app ever downloads or refreshes the list. Running this on a newer list is a new
snapshot, which changes passwords, so it must ship as a new algorithm version (see ALGORITHM.md).
The output keeps every rule (ICANN and PRIVATE sections), drops comments and blank lines, and
refuses input that isn't already NFKC-lowercase (the site rule matches on NFKC-lowercase text).
"""
import hashlib, os, re, sys, unicodedata

src = open(sys.argv[1], encoding="utf-8").read()
version = re.search(r"^// VERSION: (\S+)", src, re.M)[1]
commit = re.search(r"^// COMMIT: (\S+)", src, re.M)[1]
upstream = hashlib.sha256(src.encode("utf-8")).hexdigest()
rules = []
for line in src.splitlines():
    line = line.strip()
    if not line or line.startswith("//"):
        continue
    rule = line.split()[0]
    if unicodedata.normalize("NFKC", rule).lower() != rule or re.search(r"[`\\$]", rule):
        sys.exit(f"unsupported rule {rule!r}")
    rules.append(rule)
if len(set(rules)) != len(rules):
    sys.exit("duplicate rules")
text = "\n".join(rules)
snap_id = "psl-" + version[:10]
out = f"""// SPDX-License-Identifier: MPL-2.0
// This file is derived from the Public Suffix List (https://publicsuffix.org/list/), which is
// licensed under the Mozilla Public License 2.0: https://mozilla.org/MPL/2.0/
// Part of Keyforge algorithm v2 (see ALGORITHM.md). FROZEN: never edit, refresh or fetch this
// list. Any change alters passwords, so a different list must be a new algorithm version.
// Generated by tools/make_psl.py. Upstream VERSION {version}, COMMIT {commit},
// upstream file SHA-256 {upstream}.
// Rules (ICANN and PRIVATE sections together), one per line: {len(rules)} rules.
export const PSL_ID = "{snap_id}";
export const PSL_SHA256 = "{hashlib.sha256(text.encode("utf-8")).hexdigest()}"; // of the rules joined with "\\n"
export const PSL_RULES = `
{text}
`;
"""
dest = os.path.join(os.path.dirname(os.path.abspath(__file__)), "..", "psl.js")
open(dest, "w", encoding="utf-8", newline="\n").write(out)
print(snap_id, len(rules), "rules,", len(out.encode()), "bytes")
